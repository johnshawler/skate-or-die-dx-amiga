#!/usr/bin/env python3
"""Generate src/autowalk.h: the control byte of every pass that walks the overworld skater from the shop door to each event exit (ecs/tools/route_plan.py on tools/overworld_model.py).
Used by test builds (-DAUTOWALK) to enter the events the way a player does."""
import sys, os
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, '..', '..', 'tools'))
import route_plan as R
names = ['ramp', 'hj', 'race', 'jam', 'joust']
out = ['/* generated by tools/make_autowalk.py */']; lens = []
for n in names:
    seq, s = R.plan(n)
    assert seq and s.exit_code, (n, s.x, s.y)
    out.append('static const unsigned char aw_%s[] = {%s};' % (n, ','.join('0x%02X' % (0xF0 | R.ctl(jx, jy)) for jx, jy in seq)))
    lens.append(len(seq)); print(n, len(seq), 'passes, exit', s.exit_code)
out.append('static const unsigned char *const aw_seq[5] = {%s};' % ','.join('aw_' + n for n in names))
out.append('static const unsigned short aw_len[5] = {%s};' % ','.join(map(str, lens)))
open(os.path.join(here, '..', 'src', 'autowalk.h'), 'w').write('\n'.join(out) + '\n')
