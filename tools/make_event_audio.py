#!/usr/bin/env python3
"""Render the NES music and effects the events use, with the original 6502 engine and the approximate APU renderer.
usage: make_event_audio.py <rom.nes> <outdir>
Songs (looped, signed 8-bit mono, 16 kHz): ramp = NES id $45, high jump = $49, downhill race = $3D, downhill jam = $41.
Effects: the IIGS driver's effect numbers are used as NES sound ids (same 0..$57 range); ids $09-$1F are rendered at 22050 Hz."""
import os, sys, struct
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import nes_sound, nes_apu
rom_path, outdir = sys.argv[1:3]
os.makedirs(outdir, exist_ok=True)
rom = nes_sound.load_rom(rom_path)

def run(sid, frames):
    m = nes_sound.Machine(rom); m.call(0x8008); m.call(0x8040, a=sid)
    for f in range(frames):
        m.frame = f; m.call(0x8245)
    return m

SONG_RATE, START = 16000, 120
for name, sid, loop in (('ev_song1', 0x45, 2560), ('ev_song2', 0x49, 2700), ('ev_song3', 0x3D, 2176), ('ev_song4', 0x41, 3456)):
    frames = START + loop + 30
    m = run(sid, frames)
    audio = nes_apu.render(m.log, frames, m.mem, sr=SONG_RATE)
    a0 = int(round(START * nes_apu.FRAME_CYC / nes_apu.CPU * SONG_RATE))
    n = int(round(loop * nes_apu.FRAME_CYC / nes_apu.CPU * SONG_RATE)) // 16 * 16
    seg = audio[a0:a0 + n].astype(np.float64); seg -= seg.mean(); seg *= 0.9 / np.max(np.abs(seg))
    open(f'{outdir}/{name}.raw', 'wb').write(np.clip(np.round(seg * 127), -127, 127).astype(np.int8).tobytes())
    print('%s: id $%02X, %d samples, %.1f s, %d KB' % (name, sid, n, n / SONG_RATE, n // 1024))

SFX_RATE = 22050
IDS = list(range(0x09, 0x20))
segs = {}; peak = 0
for sid in IDS:
    frames = 200
    m = run(sid, frames)
    last = max(f for f, r, v in m.log)
    nf = last + 8
    audio = nes_apu.render(m.log, nf, m.mem, sr=SFX_RATE).astype(np.float64)
    audio -= audio.mean()
    idx = np.nonzero(np.abs(audio) > 0.01 * max(1e-9, np.max(np.abs(audio))))[0]
    audio = audio[:idx[-1] + 1] if len(idx) else audio[:2]
    segs[sid] = audio; peak = max(peak, np.max(np.abs(audio)))
blob = b''; table = []
for sid in IDS:
    a = segs[sid] * (0.9 / peak)
    pcm = np.clip(np.round(a * 127), -127, 127).astype(np.int8).tobytes()
    pcm += b'\0' * (-len(pcm) % 4)
    table.append((sid, len(blob), len(pcm))); blob += pcm
open(f'{outdir}/sfx.raw', 'wb').write(blob)
with open(f'{outdir}/ev_audio.h', 'w') as f:
    f.write('/* generated by tools/make_event_audio.py: effect id -> offset/length in sfx.raw (22050 Hz, signed 8-bit) */\n')
    f.write('#define SFX_FIRST 0x%02X\n#define SFX_COUNT %d\n' % (IDS[0], len(IDS)))
    f.write('static const u32 sfx_tab[SFX_COUNT][2] = {\n' + ',\n'.join('    {%d, %d}  /* $%02X */' % (o, l, s) for s, o, l in table) + '\n};\n')
print('sfx: %d effects, %d KB' % (len(IDS), len(blob) // 1024))
