#!/usr/bin/env python3
"""Generate the tables the menu logic (demo/src/menu.h) takes from overlay F39, and the planar glyph font.
usage: python3 -I tools/make_menu_data.py <resdir> <out_include.h> <out_font.bin>
Everything is read from the decompressed resources (work/res/F39.bin loaded at 03:1000, F2.bin = font at 02:0000)."""
import sys
res, out_h, out_font = sys.argv[1:4]
f39 = open(f'{res}/F39.bin', 'rb').read(); f2 = open(f'{res}/F2.bin', 'rb').read()
B = 0x1000
def w(a): return f39[a - B] | f39[a - B + 1] << 8
def cstr(a):
    o = a - B; return f39[o:f39.index(0, o)]
def arr(name, vals, typ='unsigned char'):
    return f'static const {typ} {name}[{len(vals)}] = {{' + ','.join(str(v) for v in vals) + '};\n'
def sarr(name, b):
    return f'static const unsigned char {name}[{len(b) + 1}] = {{' + ','.join(str(v) for v in b) + ',0};\n'

h = ['/* Generated by tools/make_menu_data.py from overlay F39: do not edit. */\n']
h.append(arr('menu_hotspots', list(f39[0x4628 - B:0x4628 - B + 70])))       # 14 x (x0, x1, y0, y1, id)
speech = b''
for i in range(21):
    a = w(0x4669 + 2 * i); speech += f39[a - B:a - B + 36]
h.append(arr('menu_speech_txt_flat', list(speech)))
h.append('static const unsigned char (*const menu_speech_txt)[36] = (const unsigned char (*)[36])menu_speech_txt_flat;\n')
h.append(arr('menu_board_y', list(f39[0x4987 - B:0x4987 - B + 10]), 'unsigned short'))
h.append(arr('menu_board_x', list(f39[0x4991 - B:0x4991 - B + 10]), 'unsigned short'))
h.append(arr('menu_colour_tab', [w(0x307A + 2 * i) for i in range(12)], 'unsigned short'))
h.append(arr('menu_hs_col', list(f39[0x4591 - B:0x4591 - B + 12])))
h.append(arr('menu_hs_row', list(f39[0x459D - B:0x459D - B + 12])))
h.append(arr('menu_hexchars', [w(0x4B2F + 2 * i) for i in range(16)]))
h.append(sarr('menu_txt_cancel', cstr(0x45AD)))
h.append(sarr('menu_txt_register', cstr(0x45C6)))
h.append(sarr('menu_txt_blank', cstr(0x45E3)))
h.append(sarr('menu_txt_clear15', cstr(0x460C)))
open(out_h, 'w').write(''.join(h))

# glyphs 0..0x5F: 8 rows x 4 bytes of 4bpp; stored as 4 bit-planes per row (one byte each, MSB = left pixel): 32 bytes per glyph
out = bytearray()
for g in range(0x60):
    base = g * 32
    for y in range(8):
        nib = []
        for x in range(4):
            b = f2[base + y * 4 + x]; nib += [b >> 4, b & 15]
        for p in range(4):
            v = 0
            for i in range(8): v = (v << 1) | ((nib[i] >> p) & 1)
            out.append(v)
open(out_font, 'wb').write(bytes(out))
print('menu data:', len(speech) // 36, 'speech strings,', len(out) // 32, 'glyphs')
